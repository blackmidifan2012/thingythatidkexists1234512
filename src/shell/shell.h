struct AppDef;

typedef enum { SCR_LOCK, SCR_HOME, SCR_APP, SCR_EXT, SCR_SWITCHER } ScreenKind;

typedef enum { TILE_SMALL, TILE_MEDIUM, TILE_WIDE } TileSize;

typedef struct Notification {
	uint32_t id;
	char *app_name, *summary, *body, *icon, *desktop_entry;
	time_t time;
	int urgency;                 /* 0 low, 1 normal, 2 critical */
	bool toasted;
	bool internal;               /* generated by the shell itself */
	bool keep;                   /* internal, but stays in the action centre (shell_post) */
	char *action_key;            /* default action to emit on tap (D-Bus apps) */
	double toast_t0;
} Notification;

typedef struct Shell {
	UI ui;
	ScreenKind screen;
	double w, h, scale;          /* logical size (dp) and pixel scale */
	int pw, ph;
	double status_h, nav_h;
	bool dirty;
	bool fullscreen_ext;         /* external app is fullscreen: hide chrome */

	Pager home_pager;            /* 0 = Start, 1 = all apps */
	bool locked;
	bool screen_off;

	/* overlays */
	double ac_pos;               /* action center open amount 0..1 */
	bool ac_target_open;
	Anim ac_anim;
	bool ac_dragging;

	/* notification store */
	VEC(Notification *) notifs;
	VEC(Notification *) toasts;  /* pending toasts, front = current */
	uint32_t next_notif_id;

	/* current built-in app / external view */
	const struct AppDef *cur_app;
	View *cur_view;
	VEC(const struct AppDef *) app_stack;   /* running built-in apps (MRU first) */

	/* transition */
	struct {
		int kind;                /* 0 none */
		double t0, dur;
		cairo_surface_t *snap_a, *snap_b;
		ScreenKind to;
		const struct AppDef *to_app;
		View *to_view;
		Rect origin;             /* tile rect the transition grows from */
		Color origin_color;
		bool back;
	} tr;

	/* launch splash while a Linux app starts */
	struct { bool active; double t0; char *name; Color color; Image *img; const struct AppDef *def; DesktopApp *app; } launching;

	double volume_hud_t;         /* time of last volume change (for the HUD) */
	Anim kbd_anim;
	double kbd_pos;
	bool kbd_forced;             /* keyboard shown manually for apps without text-input */

	double last_input;
	double nav_peek_until;       /* nav bar temporarily shown over a fullscreen app */
} Shell;

